from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from dyadtetrade.api.main import app

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "frontend" / "src" / "api" / "openapi.generated.ts"
SNAPSHOT = ROOT / "reports" / "openapi.json"


def ts_type(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return str(schema["$ref"]).rsplit("/", 1)[-1]
    if "anyOf" in schema:
        return " | ".join(ts_type(item) for item in schema["anyOf"])
    if "enum" in schema:
        return " | ".join(json.dumps(item, ensure_ascii=False) for item in schema["enum"])
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{ts_type(schema.get('items', {}))}>"
    if kind == "object":
        additional = schema.get("additionalProperties")
        if isinstance(additional, dict):
            return f"Record<string, {ts_type(additional)}>"
        return "Record<string, unknown>"
    return {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "null": "null",
    }.get(str(kind), "unknown")


def render(openapi: dict[str, Any]) -> str:
    lines = [
        "/* This file is generated by scripts/generate_openapi_types.py. Do not edit manually. */",
        f"export const OPENAPI_VERSION = {json.dumps(openapi.get('openapi'))} as const",
        "",
    ]
    schemas = openapi.get("components", {}).get("schemas", {})
    for name in sorted(schemas):
        schema = schemas[name]
        if schema.get("type") != "object" or not schema.get("properties"):
            lines.append(f"export type {name} = {ts_type(schema)}")
            lines.append("")
            continue
        required = set(schema.get("required", []))
        lines.append(f"export interface {name} {{")
        for field, field_schema in schema["properties"].items():
            optional = "" if field in required else "?"
            lines.append(f"  {json.dumps(field)}{optional}: {ts_type(field_schema)}")
        lines.append("}")
        lines.append("")
    lines.append("export interface ApiOperations {")
    for path in sorted(openapi.get("paths", {})):
        for method in sorted(openapi["paths"][path]):
            operation = openapi["paths"][path][method]
            operation_id = operation.get("operationId")
            if operation_id:
                operation_key = json.dumps(operation_id)
                method_value = json.dumps(method.upper())
                path_value = json.dumps(path)
                lines.append(f"  {operation_key}: {{ method: {method_value}; path: {path_value} }}")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main() -> int:
    schema = app.openapi()
    text = render(schema)
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    SNAPSHOT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(text, encoding="utf-8")
    SNAPSHOT.write_text(json.dumps(schema, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"generated {OUTPUT.relative_to(ROOT)} from {len(schema.get('paths', {}))} paths")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
